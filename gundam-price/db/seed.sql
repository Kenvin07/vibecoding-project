--   注：PRD.md 里的"本期 3 台"因此需要同步更新，这件事还没做（留给后续）。
--
-- 【为什么没有「历史走势」数据】契约第 2.2 节写明：详情页的「近 30 天每日最低价
--   走势」由本表按 updatedDate 分组取 MIN(price) 算出来，不单独建表、不单独存。
--   所以 data.json 里那个 history 字段不该进库，它是"算出来的"不是"存下来的"。
-- ============================================================================


